# 两边会不一样。
# 每套数据**在这 8 拍上的平均值**（= 原工具算"整体增益"时用的那个均值）。
#
# 原工具的整体增益是**绕均值**放大的：腿摆幅 ×1.5 意思是"围绕平均位置摆得更大"，
# 不是"角度乘 1.5"。绕 0 放大就会打拳（用户 2026-10-14 投诉过，见 `anim.mod_means`）。
# 所以 `layers.Gait` 照抄时要补一项常数偏移 `mdev × 原增益 × (1 − 倍数)` ——
# 腿那两路能到 2~4°，64px 上够错一个像素。全 1.0 倍数时这一项自动为 0。
